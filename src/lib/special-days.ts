/**
 * 특별일 데이터가 커버하는 연도 범위.
 * 예약 가능 기간(오늘 + 365일)이 이 범위를 벗어나면 데이터를 확장해야 한다.
 * 범위 밖 날짜는 조용히 "일반일"로 처리하지 않고 supported=false로 명시한다.
 */
export const SUPPORTED_YEARS = { min: 2026, max: 2028 } as const;

/** 해당 날짜가 특별일 데이터 지원 범위 안인지 확인한다 */
export function isYearSupported(dateStr: string): boolean {
  const year = Number(dateStr.slice(0, 4));
  return Number.isFinite(year) && year >= SUPPORTED_YEARS.min && year <= SUPPORTED_YEARS.max;
}

export interface SpecialDayMeta {
  date: string;
  isWeekend: boolean;
  isHoliday: boolean;
  isSonEomneunDay: boolean;
  /** 공휴일명 (고객 캘린더 표시용) */
  holidayName: string | null;
  /**
   * 고객 캘린더에 표시할 짧은 배지.
   * 가격과 연결한 문구는 절대 쓰지 않는다.
   */
  customerBadge: string | null;
  /**
   * 공휴일/손없는날 데이터가 이 날짜를 커버하는지 여부.
   * false이면 isHoliday/isSonEomneunDay 판정을 신뢰할 수 없다.
   * (주말 판정은 연도와 무관하게 항상 정확하다)
   */
  supported: boolean;
}

/** YYYY-MM-DD 문자열의 요일을 UTC 기준으로 안전하게 판정한다 */
function weekdayOf(dateStr: string): number {
  const [y, m, d] = dateStr.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d)).getUTCDay();
}

/**
 * 날짜의 특별일 메타데이터를 반환한다.
 * 견적 엔진과 캘린더가 모두 이 함수를 사용한다.
 */
export function getSpecialDayMeta(dateStr: string): SpecialDayMeta {
  const wd = weekdayOf(dateStr);
  const isWeekend = wd === 0 || wd === 6;
  const supported = isYearSupported(dateStr);

  const holidayName = HOLIDAYS[dateStr] ?? null;
  const isHoliday = holidayName !== null;
  const isSonEomneunDay = SON_EOMNEUN_DAYS.has(dateStr);

  // 배지 우선순위: 공휴일명 > 손없는날 (주말은 캘린더가 요일 컬럼으로 이미 구분)
  let customerBadge: string | null = null;
  if (isHoliday) customerBadge = holidayName;
  else if (isSonEomneunDay) customerBadge = "손없는날";

  return { date: dateStr, isWeekend, isHoliday, isSonEomneunDay, holidayName, customerBadge, supported };
}

/**
 * 날짜 조건에 따른 내부 가격 보정액을 반환한다.
 *
 * 조건이 몇 개 겹치든 DATE_ADJUSTMENT_AMOUNT를 한 번만 반환한다.
 * (토요일 + 손없는날 → 30,000원. 60,000원이 아니다)
 */
export function getDateAdjustment(dateStr: string | null | undefined): number {
  if (!dateStr) return 0;
  const meta = getSpecialDayMeta(dateStr);
  const applies = meta.isWeekend || meta.isHoliday || meta.isSonEomneunDay;
  return applies ? DATE_ADJUSTMENT_AMOUNT : 0;
}

/** 내부 감사용 — 보정이 적용됐는지 여부만 반환 */
export function isDateAdjustmentApplied(dateStr: string | null | undefined): boolean {
  return getDateAdjustment(dateStr) > 0;
}

/**
 * 특별일 데이터 지원 범위를 벗어난 날짜에 대해 throw한다.
 *
 * 공휴일/손없는날을 조용히 "없음"으로 처리하면 가격이 잘못 계산되므로,
 * 견적 확정과 예약 생성 경로에서는 반드시 이 검증을 거친다.
 * 데이터를 확장하려면 scripts/generate-special-days.mjs를 실행한다.
 */
export class UnsupportedDateError extends Error {
  code = "DATE_NOT_SUPPORTED";
  constructor(dateStr: string) {
    super(
      `${dateStr}는 현재 예약 가능한 기간이 아닙니다. 해당 날짜는 상담 접수를 통해 문의해주세요.`
    );
    this.name = "UnsupportedDateError";
  }
}

export function assertDateSupported(dateStr: string | null | undefined): void {
  if (!dateStr) return;
  if (!isYearSupported(dateStr)) throw new UnsupportedDateError(dateStr);
}
