/** 3종 동의 입력값 */
export interface AgreementConsent {
  corePrinciplesAgreed: boolean;
  serviceTermsAgreed: boolean;
  additionalChargeAgreed: boolean;
}

/**
 * 3종 동의가 모두 완료됐는지 서버에서 검증한다.
 * 클라이언트 검증만으로 처리하지 않는다.
 */
export function isAllAgreed(consent: Partial<AgreementConsent> | null | undefined): boolean {
  return (
    consent?.corePrinciplesAgreed === true &&
    consent?.serviceTermsAgreed === true &&
    consent?.additionalChargeAgreed === true
  );
}

/**
 * 동의서 원문이 실제로 준비됐는지 검증한다.
 *
 * AGREEMENT_CONTENT_READY 플래그뿐 아니라 sections 1~11의 body가
 * 실제로 채워졌는지도 함께 확인한다. 플래그만 true로 바꾸고 본문이 비어 있으면
 * 고객이 빈 약관에 동의하게 되므로 이를 방지한다.
 */
export function isAgreementContentReady(): boolean {
  if (!AGREEMENT_CONTENT_READY) return false;
  if (AGREEMENT_SECTIONS.length !== 11) return false;
  return AGREEMENT_SECTIONS.every((sec) => sec.body.trim().length > 0);
}

/** 미동의 항목 라벨 목록 (오류 메시지용) */
export function missingAgreements(consent: Partial<AgreementConsent> | null | undefined): string[] {
  const missing: string[] = [];
  if (consent?.corePrinciplesAgreed !== true) missing.push("안내 핵심 원칙");
  if (consent?.serviceTermsAgreed !== true) missing.push("청소 서비스 이용 및 현장 추가사항 안내");
  if (consent?.additionalChargeAgreed !== true) missing.push("견적 및 추가요금 안내");
  return missing;
}
